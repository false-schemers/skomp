#!/bin/bash
# skomp end-to-end tests.  Run from the repository root, after `make':
#
#   bash test/run-tests.sh
#
# Each test/NAME.scm is compiled for the native target, run, and its output
# compared with test/NAME.oracle.  The WebAssembly target is exercised too when
# a wasm host is installed, and skipped when none is.  Nothing here needs the
# tree to be installed: ./skomp finds ./skomp-home beside itself.
set -u

# The Windows build writes skomp.exe, the Un*x one skomp. [cco]
if [ -z "${SKOMP:-}" ]; then
  if [ -x ./skomp.exe ]; then SKOMP=./skomp.exe; else SKOMP=./skomp; fi
fi
WORK=$(mktemp -d "${TMPDIR:-/tmp}/skomp-test.XXXXXX")
pass=0; fail=0; skip=0

say()  { printf '%s\n' "$*"; }
ok()   { pass=$((pass+1)); printf '  [ok]   %s\n' "$1"; }
bad()  { fail=$((fail+1)); printf '  [FAIL] %s\n' "$1"; shift; for l in "$@"; do printf '         %s\n' "$l"; done; }
skipt(){ skip=$((skip+1)); printf '  [skip] %s -- %s\n' "$1" "$2"; }
# A linker names the product: MSVC's /Fe adds .exe to a name without a
# suffix, so a test that runs what it compiled has to look for both. [cco]
runp() { if [ -x "$1" ]; then "$1"; else "$1.exe"; fi; }

cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

if [ ! -x "$SKOMP" ]; then
  say "run-tests: $SKOMP is not there; run make first"
  exit 1
fi

# ------------------------------------------------------------------ programs
say "=== programs (native target) ==="
for src in test/*.scm; do
  name=$(basename "$src" .scm)
  oracle="test/$name.oracle"
  if [ ! -f "$oracle" ]; then skipt "$name" "no oracle"; continue; fi
  if ! "$SKOMP" -o "$WORK/$name" "$src" > "$WORK/$name.cerr" 2>&1; then
    bad "$name (compile)" "$(head -3 "$WORK/$name.cerr")"
    continue
  fi
  # a program may write files, so run it in a directory of its own.  $WORK is
  # absolute (mktemp -d), so the binary is still named correctly from there.
  mkdir -p "$WORK/run-$name"
  if ! ( cd "$WORK/run-$name" && "$WORK/$name" ) > "$WORK/$name.out" 2>&1; then
    bad "$name (run)" "$(tail -3 "$WORK/$name.out")"
    continue
  fi
  if diff -q <(tr -d '\r' < "$oracle") <(tr -d '\r' < "$WORK/$name.out") >/dev/null; then
    ok "$name"
  else
    bad "$name (output)" $(diff <(tr -d '\r' < "$oracle") <(tr -d '\r' < "$WORK/$name.out") | head -6)
  fi
done

# ------------------------------------------------------------------ modes
say "=== modes ==="

# -S writes a MARV module and stops
if "$SKOMP" -S -o "$WORK/m.mvs" test/t01-base.scm >/dev/null 2>&1 &&
   head -1 "$WORK/m.mvs" | grep -q "generated by (skint compile)"; then
  ok "-S writes a .mvs"
else
  bad "-S writes a .mvs"
fi

# -c writes a target object and stops
cp test/t01-base.scm "$WORK/obj.scm"
if "$SKOMP" -c "$WORK/obj.scm" >/dev/null 2>&1 && [ -s "$WORK/obj.c" ]; then
  ok "-c writes an object beside the input"
else
  bad "-c writes an object beside the input"
fi
if "$SKOMP" -c -o "$WORK/named.c" "$WORK/obj.scm" >/dev/null 2>&1 &&
   [ -s "$WORK/named.c" ]; then
  ok "-c honours -o"
else
  bad "-c honours -o"
fi

# without -o the executable is named after the input and the target, which is
# what SRFI 138 asks of compile-r7rs: prog.scm compiles to prog
cp test/t01-base.scm "$WORK/derived.scm"
if "$SKOMP" "$WORK/derived.scm" > "$WORK/derived.err" 2>&1 &&
   { [ -s "$WORK/derived" ] || [ -s "$WORK/derived.exe" ]; }; then
  ok "no -o names the executable after the input"
else
  bad "no -o names the executable after the input" "$(head -2 "$WORK/derived.err")"
fi

# -M into a fresh directory builds; into a non-empty one is refused.
# Which makefile MARV writes, and which tool builds it, follow from the
# target: a cl target gets an nmakefile for nmake, everything else a
# Makefile for make.  Neither tool is required to be installed.  nmake is
# given dash flags because a Git Bash reads /nologo as a path and rewrites
# it. [cco]
if ! "$SKOMP" -M "$WORK/mk" -o app test/t01-base.scm >/dev/null 2>&1; then
  bad "-M builds a self-contained directory" "skomp -M failed"
elif [ -f "$WORK/mk/nmakefile" ]; then
  if ! command -v nmake >/dev/null 2>&1; then
    skipt "-M builds a self-contained directory" "nmake is not installed"
  elif (cd "$WORK/mk" && nmake -nologo -f nmakefile >/dev/null 2>&1) &&
       [ -s "$WORK/mk/app.exe" ]; then
    ok "-M builds a self-contained directory"
  else
    bad "-M builds a self-contained directory" "nmake did not build app.exe"
  fi
elif [ -f "$WORK/mk/Makefile" ]; then
  if ! command -v make >/dev/null 2>&1; then
    skipt "-M builds a self-contained directory" "make is not installed"
  elif make -s -C "$WORK/mk" >/dev/null 2>&1 && [ -x "$WORK/mk/app" ]; then
    ok "-M builds a self-contained directory"
  else
    bad "-M builds a self-contained directory" "make did not build app"
  fi
else
  bad "-M builds a self-contained directory" "no makefile was written"
fi
mkdir -p "$WORK/mk2" && : > "$WORK/mk2/occupied"
if "$SKOMP" -M "$WORK/mk2" -o app test/t01-base.scm > "$WORK/mk2.err" 2>&1; then
  bad "-M refuses a non-empty directory" "it did not refuse"
elif grep -q "not an empty directory" "$WORK/mk2.err"; then
  ok "-M refuses a non-empty directory"
else
  bad "-M refuses a non-empty directory" "$(head -2 "$WORK/mk2.err")"
fi

# a second input file is an error
if "$SKOMP" -o "$WORK/two" test/t01-base.scm test/t01-base.scm \
     > "$WORK/two.err" 2>&1; then
  bad "two inputs are refused" "it did not refuse"
elif grep -q "more than one input file" "$WORK/two.err"; then
  ok "two inputs are refused"
else
  bad "two inputs are refused" "$(head -2 "$WORK/two.err")"
fi

# a .mvh in the working directory would shadow the runtime's own
mkdir -p "$WORK/shadow/lib" && : > "$WORK/shadow/lib/scmrt.mvh"
HERE=$PWD
if ( cd "$WORK/shadow" && "$HERE/$SKOMP" -o out "$HERE/test/t01-base.scm" ) \
     > "$WORK/shadow.err" 2>&1; then
  bad "a shadowing .mvh is refused" "it did not refuse"
elif grep -q "would be used instead of my own" "$WORK/shadow.err"; then
  ok "a shadowing .mvh is refused"
else
  bad "a shadowing .mvh is refused" "$(head -2 "$WORK/shadow.err")"
fi

# --version names all four parts
if "$SKOMP" --version | grep -q "^skomp " &&
   "$SKOMP" --version | grep -q "skint " &&
   "$SKOMP" --version | grep -q "marv " &&
   "$SKOMP" --version | grep -q "wcpl "; then
  ok "--version names all four parts"
else
  bad "--version names all four parts"
fi

# a compile error must come back non-zero
printf '(import (scheme base))\n(no-such-name 1)\n' > "$WORK/bad.scm"
if "$SKOMP" -o "$WORK/bad" "$WORK/bad.scm" >/dev/null 2>&1; then
  bad "a compile error exits non-zero" "it exited 0"
else
  ok "a compile error exits non-zero"
fi

# ------------------------------------------------------------------ features
say "=== features ==="

# `debug' is a feature by default, so (srfi 145)'s assume checks its
# expression; -D NDEBUG takes it away, and the same program runs through.
printf '%s\n' \
  '(import (scheme base) (scheme write) (srfi 145))' \
  '(define (f x) (assume (number? x) "not a number") (display "ok") (newline))' \
  '(f "s")' > "$WORK/assume.scm"
if ! "$SKOMP" -o "$WORK/assume" "$WORK/assume.scm" > "$WORK/assume.err" 2>&1; then
  bad "assume checks with the default features" "$(head -2 "$WORK/assume.err")"
elif runp "$WORK/assume" > "$WORK/assume.out" 2>&1; then
  bad "assume checks with the default features" "it exited 0"
elif grep -q "Assumption failed" "$WORK/assume.out"; then
  ok "assume checks with the default features"
else
  bad "assume checks with the default features" "$(head -2 "$WORK/assume.out")"
fi
if "$SKOMP" -D NDEBUG -o "$WORK/nassume" "$WORK/assume.scm" >/dev/null 2>&1 &&
   runp "$WORK/nassume" > "$WORK/nassume.out" 2>&1 &&
   tr -d '\r' < "$WORK/nassume.out" | grep -q '^ok$'; then
  ok "-D NDEBUG compiles the assumption away"
else
  bad "-D NDEBUG compiles the assumption away" "$(head -2 "$WORK/nassume.out")"
fi

# and NDEBUG reaches the backend as well, where the target's ~D says it goes
if "$SKOMP" -n -v -D NDEBUG -o "$WORK/nd" "$WORK/assume.scm" 2>&1 |
     grep -q -- "-DNDEBUG"; then
  ok "-D NDEBUG reaches the target compiler"
else
  bad "-D NDEBUG reaches the target compiler" "no -DNDEBUG in the backend command"
fi

# a -D name of the caller's own is a cond-expand feature and nothing more
printf '%s\n' \
  '(import (scheme base) (scheme write))' \
  '(cond-expand (my-build (display "with")) (else (display "without")))' \
  '(newline)' > "$WORK/feat.scm"
if "$SKOMP" -D my-build -o "$WORK/feat" "$WORK/feat.scm" >/dev/null 2>&1 &&
   runp "$WORK/feat" > "$WORK/feat.out" 2>&1 &&
   tr -d '\r' < "$WORK/feat.out" | grep -q '^with$'; then
  ok "-D adds a cond-expand feature"
else
  bad "-D adds a cond-expand feature" "$(head -2 "$WORK/feat.out")"
fi

# and the program's own (features) answers the same list cond-expand was told
printf '%s\n' \
  '(import (scheme base) (scheme write))' \
  '(write (features))' \
  '(newline)' > "$WORK/flist.scm"
if "$SKOMP" -D my-build -o "$WORK/flist" "$WORK/flist.scm" >/dev/null 2>&1 &&
   runp "$WORK/flist" > "$WORK/flist.out" 2>&1 &&
   grep -q "my-build" "$WORK/flist.out" && grep -q "debug" "$WORK/flist.out"; then
  ok "(features) answers the compiled feature list"
else
  bad "(features) answers the compiled feature list" "$(head -2 "$WORK/flist.out")"
fi

# a -D name that is not one is refused before anything is compiled
if "$SKOMP" -D 'no such feature' -o "$WORK/x" "$WORK/feat.scm" \
     > "$WORK/dbad.err" 2>&1; then
  bad "a -D name that needs quoting is refused" "it did not refuse"
elif grep -q "a feature name takes" "$WORK/dbad.err"; then
  ok "a -D name that needs quoting is refused"
else
  bad "a -D name that needs quoting is refused" "$(head -2 "$WORK/dbad.err")"
fi

# ------------------------------------------------------------------ packaging
say "=== packaging ==="

# marv's own lib/ is not shipped, which holds only while generated modules
# name no system module but the Scheme runtime's two.
sysmods=$("$SKOMP" -S -o "$WORK/sys.mvs" test/t03-srfi.scm >/dev/null 2>&1 &&
          grep -o '(include system \$[a-z.]*)' "$WORK/sys.mvs" | sort -u)
unexpected=$(printf '%s\n' "$sysmods" |
             grep -v -e '^(include system \$scmrt)$' -e '^(include system \$scmi)$' |
             grep -v '^$')
if [ -z "$unexpected" ]; then
  ok "generated modules name only \$scmrt and \$scmi"
else
  bad "generated modules name only \$scmrt and \$scmi" "$unexpected" \
      "marv's lib/ would have to be imported too (see pre/README.md)"
fi

# clib/ carries every library a compiled program may import, since skomp ships
# it and nothing else of the host's library tree.  The import refuses to run
# when a shadowed name has no file there; this checks the two still agree, and
# counts rather than comparing with a constant that would rot.  The name list
# is read by paren balance: a line-range match runs past the end of the form.
shadow_names() {
  awk '
    /^\(define \*shadow-library-names\*/ { inl = 1 }
    inl { print
          t = $0; gsub(/[^(]/, "", t); o += length(t)
          t = $0; gsub(/[^)]/, "", t); c += length(t)
          if (o > 0 && o == c) exit }
  ' lib/skint/compile/cups-front.scm | grep -oE '\([a-z]+( [a-z0-9-]+)+\)'
}
if [ -d lib/skint/compile/clib ]; then
  files=$(find lib/skint/compile/clib -name '*.sld' | wc -l)
  names=$(shadow_names | wc -l)
  if [ "$files" -gt 0 ] && [ "$files" -eq "$names" ]; then
    ok "clib holds one file per shadowed name ($files)"
  else
    bad "clib holds one file per shadowed name" \
        "$files files, $names shadowed names" \
        "re-run pre/import.ssc, and delete any clib file no longer shadowed"
  fi
else
  bad "clib is present"
fi

# ------------------------------------------------------------------ wasm
say "=== WebAssembly target ==="
WASMRUN=
if command -v wasmtime >/dev/null 2>&1; then
  WASMRUN="wasmtime run"
elif command -v node >/dev/null 2>&1; then
  WASMRUN="node_wasi"
fi
run_wasm() {   # $1 = .wasm path
  if [ "$WASMRUN" = "node_wasi" ]; then
    node -e '
      const fs=require("fs"), {WASI}=require("wasi");
      const w=new WASI({version:"preview1",args:["prog"],env:{},preopens:{".":"."}});
      (async()=>{const m=await WebAssembly.compile(fs.readFileSync(process.argv[1]));
      const i=await WebAssembly.instantiate(m,w.getImportObject());w.start(i);})();
    ' "$1" 2>/dev/null
  else
    $WASMRUN "$1" 2>/dev/null
  fi
}
if [ -z "$WASMRUN" ]; then
  skipt "wasm" "neither wasmtime nor node is installed"
else
  for name in t01-base t03-srfi t04-unicode; do
    src="test/$name.scm"
    oracle="test/$name.oracle"
    [ -f "$src" ] && [ -f "$oracle" ] || continue
    if ! "$SKOMP" -t wcpl -o "$WORK/$name.wasm" "$src" > "$WORK/$name.werr" 2>&1; then
      bad "$name (wasm compile)" "$(grep -v '^# ' "$WORK/$name.werr" | tail -3)"
      continue
    fi
    run_wasm "$WORK/$name.wasm" > "$WORK/$name.wout" 2>&1
    if diff -q <(tr -d '\r' < "$oracle") <(tr -d '\r' < "$WORK/$name.wout") \
         >/dev/null; then
      ok "$name (wasm)"
    else
      bad "$name (wasm output)" \
          $(diff <(tr -d '\r' < "$oracle") <(tr -d '\r' < "$WORK/$name.wout") | head -6)
    fi
  done
fi

say ""
say "pass: $pass  fail: $fail  skip: $skip"
[ "$fail" -eq 0 ]
